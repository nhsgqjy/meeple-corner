CREATE TABLE games (
  id TEXT PRIMARY KEY NOT NULL, title TEXT NOT NULL, category TEXT NOT NULL,
  players TEXT NOT NULL, minutes INTEGER NOT NULL, complexity TEXT NOT NULL DEFAULT '轻松',
  description TEXT NOT NULL DEFAULT '', symbol TEXT NOT NULL DEFAULT '✦',
  accent TEXT NOT NULL DEFAULT 'sage', cover_url TEXT NOT NULL DEFAULT '',
  featured INTEGER NOT NULL DEFAULT 0, created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE voting_rounds (
  id TEXT PRIMARY KEY NOT NULL, title TEXT NOT NULL, is_active INTEGER NOT NULL DEFAULT 1,
  created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP, closed_at TEXT
);
CREATE TABLE votes (
  game_id TEXT NOT NULL REFERENCES games(id) ON DELETE CASCADE, user_id TEXT NOT NULL,
  created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP, PRIMARY KEY(game_id,user_id)
);
CREATE TABLE ratings (
  game_id TEXT NOT NULL REFERENCES games(id) ON DELETE CASCADE, user_id TEXT NOT NULL,
  score INTEGER NOT NULL, comment TEXT NOT NULL DEFAULT '',
  updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP, PRIMARY KEY(game_id,user_id)
);
CREATE TABLE round_votes (
  round_id TEXT NOT NULL REFERENCES voting_rounds(id) ON DELETE CASCADE,
  user_id TEXT NOT NULL, game_id TEXT NOT NULL REFERENCES games(id) ON DELETE CASCADE,
  created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP, PRIMARY KEY(round_id,user_id,game_id)
);
